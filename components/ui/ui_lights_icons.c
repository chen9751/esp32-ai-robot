/*
 * Official Remix Icon geometry rasterized from these SVGs:
 *   Others/sofa-line.svg
 *   Device/computer-line.svg
 *   Map/hotel-bed-line.svg
 *   Others/lightbulb-line.svg
 *   Device/tv-line.svg
 *   Design/drop-line.svg
 *   Business/window-line.svg
 *   Weather/sun-line.svg
 *   Weather/temp-hot-line.svg
 *   Design/palette-line.svg
 *
 * One-bit masks are expanded once to LVGL A8. Semantic icons on the Lights
 * page must use this approved set, never one-off LVGL geometry.
 */
static void expand_a1(const uint8_t *src, size_t src_len, uint8_t *dst, size_t pixels)
{
    size_t di=0;
    for(size_t si=0; si<src_len && di<pixels; ++si)
        for(int bit=7; bit>=0 && di<pixels; --bit)
            dst[di++]=(src[si] & (1u<<bit)) ? 0xffu : 0u;
}

