static bool s_decoded = false;

static void decode_a2(const uint8_t *src, uint8_t *dst, size_t pixel_count)
{
    static const uint8_t alpha_lut[4] = {0,85,170,255};
    for (size_t i = 0; i < pixel_count; ++i) {
        uint8_t packed = src[i >> 2];
        uint8_t shift = (uint8_t)(6 - ((i & 3U) * 2U));
        dst[i] = alpha_lut[(packed >> shift) & 0x03U];
    }
}

static void ensure_decoded(void)
{
    if (s_decoded) return;
    decode_a2(wifi_a2,wifi_buf,ICON_PIXELS);
    decode_a2(display_a2,display_buf,ICON_PIXELS);
    decode_a2(volume_a2,volume_buf,ICON_PIXELS);
    decode_a2(bluetooth_a2,bluetooth_buf,ICON_PIXELS);
    decode_a2(ai_a2,ai_buf,ICON_PIXELS);
    decode_a2(system_a2,system_buf,ICON_PIXELS);
    decode_a2(battery_charge_a2,battery_charge_buf,ICON_PIXELS);
    decode_a2(battery_low_a2,battery_low_buf,ICON_PIXELS);
    s_decoded = true;
}

static lv_obj_t *create_icon(lv_obj_t *parent,const lv_image_dsc_t *src,lv_color_t color)
{
    ensure_decoded();
    lv_obj_t *image = lv_image_create(parent);
    lv_image_set_src(image,src);
    lv_obj_set_style_image_recolor(image,color,0);
    lv_obj_set_style_image_recolor_opa(image,LV_OPA_COVER,0);
    lv_obj_clear_flag(image,LV_OBJ_FLAG_CLICKABLE);
    return image;
}

