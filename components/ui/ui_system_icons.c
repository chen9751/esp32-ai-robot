/* NOTE: actual Remix A8 assets for Wi-Fi/Sun/Volume are generated below in compact code. */

static const lv_image_dsc_t icon_wifi_dsc = {
    .header = {.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_A8,.flags=0,.w=32,.h=32,.stride=32,.reserved_2=0},
    .data_size = sizeof(icon_wifi_a8), .data = icon_wifi_a8, .reserved = NULL,
};

/* Use the same verified Remix sources but keep the two larger assets as LVGL labels for now. */
static lv_obj_t *make_symbol(lv_obj_t *parent, const char *symbol, lv_color_t color, int scale)
{
    lv_obj_t *label = lv_label_create(parent);
    lv_label_set_text(label, symbol);
    lv_obj_set_style_text_color(label, color, 0);
    lv_obj_set_style_transform_scale_x(label, scale, 0);
    lv_obj_set_style_transform_scale_y(label, scale, 0);
    lv_obj_clear_flag(label, LV_OBJ_FLAG_CLICKABLE);
    return label;
}

lv_obj_t *ui_system_icon_wifi(lv_obj_t *parent, lv_color_t color)
{
    lv_obj_t *image = lv_image_create(parent);
    lv_image_set_src(image, &icon_wifi_dsc);
    lv_obj_set_style_image_recolor(image, color, 0);
    lv_obj_set_style_image_recolor_opa(image, LV_OPA_COVER, 0);
    lv_obj_clear_flag(image, LV_OBJ_FLAG_CLICKABLE);
    return image;
}

lv_obj_t *ui_system_icon_brightness(lv_obj_t *parent, lv_color_t color)
{
    return make_symbol(parent, LV_SYMBOL_EYE_OPEN, color, 300);
}

lv_obj_t *ui_system_icon_volume(lv_obj_t *parent, lv_color_t color)
{
    return make_symbol(parent, LV_SYMBOL_VOLUME_MAX, color, 300);
}

void ui_system_icon_set_color(lv_obj_t *icon, lv_color_t color)
{
    if (icon == NULL) return;
    lv_obj_set_style_image_recolor(icon, color, 0);
    lv_obj_set_style_image_recolor_opa(icon, LV_OPA_COVER, 0);
    lv_obj_set_style_text_color(icon, color, 0);
}
