static bool ready = false;

static void expand_a1(const uint8_t *src, uint8_t *dst)
{
    for (size_t i = 0; i < A1_BYTES; ++i) {
        for (unsigned bit = 0; bit < 8; ++bit) dst[i * 8 + bit] = (src[i] & (0x80u >> bit)) ? 255 : 0;
    }
}

static void ensure_ready(void)
{
    if (ready) return;
    expand_a1(power_a1, power_a8);
    expand_a1(input_a1, input_a8);
    expand_a1(home_a1, home_a8);
    expand_a1(back_a1, back_a8);
    expand_a1(settings_a1, settings_a8);
    expand_a1(display_a1, display_a8);
    expand_a1(add_a1, add_a8);
    expand_a1(subtract_a1, subtract_a8);
    ready = true;
}

static const lv_image_dsc_t *icon_dsc(ui_remote_icon_t icon)
{
    switch (icon) {
        case UI_REMOTE_ICON_POWER: return &power_dsc;
        case UI_REMOTE_ICON_INPUT: return &input_dsc;
        case UI_REMOTE_ICON_HOME: return &home_dsc;
        case UI_REMOTE_ICON_BACK: return &back_dsc;
        case UI_REMOTE_ICON_SETTINGS: return &settings_dsc;
        case UI_REMOTE_ICON_DISPLAY: return &display_dsc;
        case UI_REMOTE_ICON_ADD: return &add_dsc;
        case UI_REMOTE_ICON_SUBTRACT: return &subtract_dsc;
        default: return &home_dsc;
    }
}

lv_obj_t *ui_remote_icon_create(lv_obj_t *parent, ui_remote_icon_t icon, lv_color_t color)
{
    ensure_ready();
    lv_obj_t *image = lv_image_create(parent);
    lv_image_set_src(image, icon_dsc(icon));
    lv_obj_set_style_image_recolor(image, color, 0);
    lv_obj_set_style_image_recolor_opa(image, LV_OPA_COVER, 0);
    lv_obj_clear_flag(image, LV_OBJ_FLAG_CLICKABLE);
    return image;
}
