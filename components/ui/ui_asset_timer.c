static void decode_rle(const uint8_t *src, size_t src_len, uint8_t *dst, size_t dst_len)
{
    size_t si = 0, di = 0;
    while (si + 1 < src_len && di < dst_len) {
        uint8_t count = src[si++];
        uint8_t value = src[si++];
        while (count-- && di < dst_len) dst[di++] = value;
    }
}

