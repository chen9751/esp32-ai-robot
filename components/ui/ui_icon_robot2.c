static uint8_t robot2_buf[ROBOT2_PIXELS];
static lv_image_dsc_t robot2_dsc = {
    .header = {
        .magic = LV_IMAGE_HEADER_MAGIC,
        .cf = LV_COLOR_FORMAT_A8,
        .flags = 0,
        .w = ROBOT2_W,
        .h = ROBOT2_H,
        .stride = ROBOT2_W,
        .reserved_2 = 0,
    },
    .data_size = sizeof(robot2_buf),
    .data = robot2_buf,
    .reserved = NULL,
};

static bool s_decoded = false;

static void ensure_decoded(void)
{
    if (s_decoded) return;
    static const uint8_t alpha_lut[4] = {0, 85, 170, 255};
    for (size_t i = 0; i < ROBOT2_PIXELS; ++i) {
        uint8_t packed = robot2_a2[i >> 2];
        uint8_t shift = (uint8_t)(6 - ((i & 3U) * 2U));
        robot2_buf[i] = alpha_lut[(packed >> shift) & 0x03U];
    }
    s_decoded = true;
}

lv_obj_t *ui_system_icon_ai_robot2(lv_obj_t *parent, lv_color_t color)
{
    ensure_decoded();
    lv_obj_t *image = lv_image_create(parent);
    lv_image_set_src(image, &robot2_dsc);
    lv_obj_set_style_image_recolor(image, color, 0);
    lv_obj_set_style_image_recolor_opa(image, LV_OPA_COVER, 0);
    lv_obj_clear_flag(image, LV_OBJ_FLAG_CLICKABLE);
    return image;
}
